const translations: Record<LanguageId, Record<MessageKey, string>> = {
  en,
  fr,
  es,
  ko,
  it,
};

let currentLanguage: LanguageId = 'en';
const listeners = new Set<() => void>();

export function isLanguageId(value: string | null | undefined): value is LanguageId {
  return LANGUAGE_IDS.includes(value as LanguageId);
}

export function getLanguage(): LanguageId {
  return currentLanguage;
}

export function getLocale(): string {
  return LANGUAGE_LOCALES[currentLanguage];
}

export function getLanguageDisplayName(): string {
  return LANGUAGE_NATIVE_NAMES[currentLanguage];
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function applyLanguage(id: LanguageId) {
  if (currentLanguage === id) return;
  currentLanguage = id;
  listeners.forEach((listener) => listener());
}

export async function loadSavedLanguage(): Promise<LanguageId> {
  try {
    const stored = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (isLanguageId(stored)) {
      applyLanguage(stored);
      return stored;
    }
  } catch {
    // Keep default.
  }
  return currentLanguage;
}

export async function persistLanguage(id: LanguageId): Promise<void> {
  applyLanguage(id);
  try {
    await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, id);
  } catch {
    // Keep in-memory selection.
  }
}

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] == null ? `{${key}}` : String(vars[key]),
  );
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const table = translations[currentLanguage] ?? en;
  return interpolate(table[key] ?? en[key] ?? key, vars);
}

export function translateOption(value: string): string {
  if (value === 'Recommend a meal') return t('chat.recommendMeal');
  if (value === 'Another idea') return t('chat.anotherIdea');
  if (value === 'Recipe') return t('chat.recipe');
  if (value === 'Yes, a full recipe') return t('chat.yesRecipe');
  if (value === 'No thanks') return t('chat.noRecipe');
  const key = `opt.${value}` as MessageKey;
  if (key in en) return t(key);
  return value;
}

export function outputLanguageInstruction(): string {
  if (currentLanguage === 'en') return '';
  return ` Write all user-visible string values in ${LANGUAGE_NATIVE_NAMES[currentLanguage]}. Keep JSON keys in English.`;
}
